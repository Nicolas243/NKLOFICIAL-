/**
 * Função global defensiva para captura de links de afiliados.
 * Procura o link manual mapeado acima; se não encontrar, gera rota de busca automática.
 */
function obterLinkAfiliado(nomeCorda, loja) {
    if (linksAfiliados[nomeCorda] && linksAfiliados[nomeCorda][loja]) {
        return linksAfiliados[nomeCorda][loja];
    }

    const termoBusca = encodeURIComponent(`corda violino ${nomeCorda}`);
    const termoGringo = encodeURIComponent(`${nomeCorda} violin strings`);

    switch(loja) {
        case 'ml': return `https://lista.mercadolivre.com.br/${termoBusca}`;
        case 'shopee': return `https://shopee.com.br/search?keyword=${termoBusca}`;
        case 'amazon': return `https://www.amazon.com.br/s?k=${termoGringo}`;
        case 'ebay': return `https://www.ebay.com/sch/i.html?_nkw=${termoGringo}`;
        default: return '#';
    }
}